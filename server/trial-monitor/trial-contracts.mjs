/**
 * Creates a validated telemetry gap record representing missed polling intervals.
 * @param {Object} params
 * @param {string} [params.id]
 * @param {number} params.startTime - Epoch timestamp where continuous telemetry paused
 * @param {number} params.endTime - Epoch timestamp where telemetry resumed
 * @param {number} [params.durationMs] - Duration in ms
 * @param {number} [params.missedIntervals] - Number of missed 60s sample cycles
 * @param {string} [params.reason] - Diagnostic explanation for telemetry gap
 * @param {number} [params.timestamp=Date.now()]
 * @returns {Object}
 */
export function createTelemetryGap({
  id = null,
  startTime,
  endTime,
  durationMs = null,
  missedIntervals = null,
  reason = 'Server offline, process downtime, or monitor cycle skipped',
  timestamp = null,
}) {
  const gapId = id || `gap-${crypto.randomUUID()}`;
  const now = Date.now();
  const start = typeof startTime === 'number' && !isNaN(startTime) ? startTime : now;
  const end = typeof endTime === 'number' && !isNaN(endTime) ? endTime : now;
  const resolvedDuration = typeof durationMs === 'number' ? Math.max(0, durationMs) : Math.max(0, end - start);
  const resolvedIntervals = typeof missedIntervals === 'number' && missedIntervals >= 1
    ? missedIntervals
    : Math.max(1, Math.floor(resolvedDuration / 60000));

  const candidate = {
    id: gapId,
    startTime: start,
    endTime: end,
    durationMs: resolvedDuration,
    missedIntervals: resolvedIntervals,
    reason: reason || 'Unknown telemetry interruption',
    timestamp: typeof timestamp === 'number' ? timestamp : now,
  };

  const validation = validateTelemetryGap(candidate);
  if (!validation.valid) {
    throw new Error(`Invalid telemetry gap: ${validation.errors.join('; ')}`);
  }

  return candidate;
}

/**
 * Validates a telemetry gap record.
 * @param {Object} gap
 * @returns {{ valid: boolean, errors: string[] }}
 */
export function validateTelemetryGap(gap) {
  const errors = [];
  if (!gap || typeof gap !== 'object') {
    return { valid: false, errors: ['Telemetry gap must be an object.'] };
  }

  if (!gap.id || typeof gap.id !== 'string') {
    errors.push('Telemetry gap must have a non-empty string "id".');
  }

  if (typeof gap.startTime !== 'number' || isNaN(gap.startTime) || gap.startTime <= 0) {
    errors.push('Telemetry gap must have a valid positive "startTime".');
  }

  if (typeof gap.endTime !== 'number' || isNaN(gap.endTime) || gap.endTime < gap.startTime) {
    errors.push('Telemetry gap "endTime" must be greater than or equal to "startTime".');
  }

  if (typeof gap.durationMs !== 'number' || gap.durationMs < 0) {
    errors.push('Telemetry gap "durationMs" must be a non-negative number.');
  }

  if (typeof gap.missedIntervals !== 'number' || gap.missedIntervals < 1) {
    errors.push('Telemetry gap "missedIntervals" must be an integer >= 1.');
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

