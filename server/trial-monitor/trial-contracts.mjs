/**
 * Validates a TelemetrySnapshot structure against invariant rules.
 * @param {Object} snapshot
 * @returns {{ valid: boolean, errors: string[] }}
 */
export function validateTelemetrySnapshot(snapshot) {
  const errors = [];
  if (!snapshot || typeof snapshot !== 'object') {
    return { valid: false, errors: ['TelemetrySnapshot must be an object.'] };
  }

  if (typeof snapshot.timestamp !== 'number' || isNaN(snapshot.timestamp) || snapshot.timestamp <= 0) {
    errors.push('TelemetrySnapshot must have a valid positive "timestamp" epoch number.');
  }

  if (snapshot.readOnlyInvariant !== true) {
    errors.push('TelemetrySnapshot must enforce readOnlyInvariant === true.');
  }

  if (!HEALTH_STATUS_LIST.includes(snapshot.overallStatus)) {
    errors.push(`Invalid overallStatus "${snapshot.overallStatus}". Expected one of: ${HEALTH_STATUS_LIST.join(', ')}.`);
  }

  // Required top-level domains
  const requiredDomains = ['systemHealth', 'agentHealth', 'orchestrationState', 'reliability', 'safety'];
  for (const domain of requiredDomains) {
    if (!snapshot[domain] || typeof snapshot[domain] !== 'object') {
      errors.push(`TelemetrySnapshot missing required domain "${domain}".`);
    }
  }

  if (snapshot.systemHealth) {
    if (snapshot.systemHealth.nodeProcess && typeof snapshot.systemHealth.nodeProcess.pid !== 'number') {
      errors.push('systemHealth.nodeProcess.pid must be a valid number.');
    }
  }

  if (snapshot.safety && snapshot.safety.emergencyStop) {
    if (typeof snapshot.safety.emergencyStop.halted !== 'boolean') {
      errors.push('safety.emergencyStop.halted must be a boolean.');
    }
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

