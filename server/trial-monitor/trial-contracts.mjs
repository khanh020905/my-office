/**
 * Deep freezes an object recursively, preventing any property mutation.
 * @template T
 * @param {T} obj
 * @returns {Readonly<T>}
 */
export function deepFreeze(obj) {
  if (obj === null || typeof obj !== 'object') return obj;
  Object.freeze(obj);
  for (const key of Object.getOwnPropertyNames(obj)) {
    const val = obj[key];
    if (val !== null && typeof val === 'object' && !Object.isFrozen(val)) {
      deepFreeze(val);
    }
  }
  return obj;
}

/**
 * Verifies that a collector component strictly adheres to the Read-Only invariant.
 * Ensures prohibited mutating methods either do not exist or throw READ_ONLY_INVARIANT_VIOLATION.
 * @param {Object} collector
 * @throws {Error} if collector attempts or exposes state mutation
 */
export function assertReadOnlyCollector(collector) {
  if (!collector || typeof collector !== 'object') {
    throw new Error('READ_ONLY_INVARIANT_VIOLATION: Invalid collector instance.');
  }

  if (collector.isReadOnly !== true) {
    throw new Error('READ_ONLY_INVARIANT_VIOLATION: Collector must declare isReadOnly: true.');
  }

  const prohibitedMutatingMethods = [
    'dispatchTask',
    'cancelExecution',
    'retryExecution',
    'sendFollowUp',
    'createMasterTask',
    'startMasterTask',
    'cancelMasterTask',
    'retrySubtask',
    'triggerEmergencyStop',
    'trip',
    'resumeEmergencyStop',
    'setAutonomyLevel',
    'updatePolicy',
    'resolveApproval',
    'createBackup',
    'restoreFromBackup',
    'appendEvent',
    'createCheckpoint',
    'registerProcess',
    'terminateProcessSafely',
  ];

  for (const method of prohibitedMutatingMethods) {
    if (typeof collector[method] === 'function') {
      try {
        collector[method]();
        // If calling succeeded without throwing, that is an invariant violation!
        throw new Error(`READ_ONLY_INVARIANT_VIOLATION: Prohibited mutating method "${method}" was callable without throwing.`);
      } catch (err) {
        if (!err.message || !err.message.includes('READ_ONLY_INVARIANT_VIOLATION')) {
          throw new Error(`READ_ONLY_INVARIANT_VIOLATION: Prohibited mutating method "${method}" did not throw READ_ONLY_INVARIANT_VIOLATION.`);
        }
      }
    }
  }

  return true;
}
