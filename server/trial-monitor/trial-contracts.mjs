/**
 * Creates a validated alert object.
 * @param {Object} params
 * @param {string} params.severity - One of ALERT_SEVERITIES (SEV-1..SEV-4)
 * @param {string} params.code - Specific machine-readable alert code
 * @param {string|Object} params.affectedTarget - Identifier or descriptor of the affected component/subsystem
 * @param {Object|string} params.evidence - Concrete operational evidence supporting the alert
 * @param {string} params.recommendedAction - Actionable operator guidance on how to remediate
 * @param {number} [params.timestamp=Date.now()] - Timestamp of the occurrence
 * @param {string} [params.id] - Optional unique alert ID (UUID generated by default)
 * @returns {Object} Validated Alert record
 */
export function createAlert({
  id = null,
  severity,
  code,
  affectedTarget,
  evidence,
  recommendedAction,
  timestamp = null,
}) {
  const alertId = id || `alert-${crypto.randomUUID()}`;
  const resolvedTimestamp = typeof timestamp === 'number' && !isNaN(timestamp) ? timestamp : Date.now();

  const candidate = {
    id: alertId,
    severity: severity || null,
    code: code || 'UNKNOWN_ALERT_CODE',
    affectedTarget: affectedTarget || 'unknown_target',
    evidence: evidence !== undefined && evidence !== null ? evidence : {},
    recommendedAction: recommendedAction || 'Review active operational logs and assess impact.',
    timestamp: resolvedTimestamp,
  };

  const validation = validateAlert(candidate);
  if (!validation.valid) {
    throw new Error(`Invalid alert: ${validation.errors.join('; ')}`);
  }

  return candidate;
}

/**
 * Validates an alert against schema rules.
 * @param {Object} alert
 * @returns {{ valid: boolean, errors: string[] }}
 */
export function validateAlert(alert) {
  const errors = [];
  if (!alert || typeof alert !== 'object') {
    return { valid: false, errors: ['Alert must be an object.'] };
  }

  if (!alert.id || typeof alert.id !== 'string') {
    errors.push('Alert must have a non-empty string "id".');
  }

  if (!ALERT_SEVERITY_LIST.includes(alert.severity)) {
    errors.push(`Invalid alert severity "${alert.severity}". Must be one of: ${ALERT_SEVERITY_LIST.join(', ')}.`);
  }

  if (!alert.code || typeof alert.code !== 'string') {
    errors.push('Alert must have a non-empty string "code".');
  }

  if (!alert.affectedTarget) {
    errors.push('Alert must have a non-empty "affectedTarget".');
  }

  if (alert.evidence === undefined || alert.evidence === null) {
    errors.push('Alert must include "evidence".');
  }

  if (!alert.recommendedAction || typeof alert.recommendedAction !== 'string') {
    errors.push('Alert must include a non-empty string "recommendedAction".');
  }

  if (typeof alert.timestamp !== 'number' || isNaN(alert.timestamp) || alert.timestamp <= 0) {
    errors.push('Alert must have a valid positive "timestamp" epoch number.');
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

